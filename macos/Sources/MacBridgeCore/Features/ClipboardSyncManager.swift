import AppKit
import CryptoKit
import Foundation

public struct PasteboardReadSample: Sendable, Equatable {
    public let changeCount: Int
    public let typeIdentifiers: Set<String>
    public let text: String?
    public let pngData: Data?

    public init(
        changeCount: Int,
        typeIdentifiers: Set<String>,
        text: String? = nil,
        pngData: Data? = nil
    ) {
        self.changeCount = changeCount
        self.typeIdentifiers = typeIdentifiers
        self.text = text
        self.pngData = pngData
    }
}

public protocol PasteboardAdapter: Sendable {
    @MainActor func currentChangeCount() -> Int
    @MainActor func readSample() -> PasteboardReadSample
    @MainActor func writeText(_ text: String)
    @MainActor func writePng(_ data: Data)
}

public final class SystemPasteboardAdapter: PasteboardAdapter, @unchecked Sendable {
    public init() {}

    @MainActor
    public func currentChangeCount() -> Int {
        NSPasteboard.general.changeCount
    }

    @MainActor
    public func readSample() -> PasteboardReadSample {
        let pb = NSPasteboard.general
        let types = Set((pb.types ?? []).map(\.rawValue))
        let text = pb.string(forType: .string)
        var pngData = pb.data(forType: .png)
        if pngData == nil,
           let tiff = pb.data(forType: .tiff),
           let rep = NSBitmapImageRep(data: tiff) {
            pngData = rep.representation(using: .png, properties: [:])
        }
        return PasteboardReadSample(
            changeCount: pb.changeCount,
            typeIdentifiers: types,
            text: text,
            pngData: pngData
        )
    }

    @MainActor
    public func writeText(_ text: String) {
        let pb = NSPasteboard.general
        pb.clearContents()
        pb.setString(text, forType: .string)
    }

    @MainActor
    public func writePng(_ data: Data) {
        let pb = NSPasteboard.general
        pb.clearContents()
        pb.setData(data, forType: .png)
    }
}

/// Feature 2: Loop-safe universal clipboard sync with password-manager filtering.
/// Updates `lastSyncedContentHash` BEFORE writing to NSPasteboard so the observer ignores its own write.
public actor ClipboardSyncManager {
    public static let concealedTypes: Set<String> = [
        "org.nspasteboard.ConcealedType",
        "org.nspasteboard.TransientType",
        "org.nspasteboard.AutoGeneratedType"
    ]
    public static let bleMaxPayloadBytes = 400
    public static let maxImageBytes = 5_242_880 // 5 MB

    private let deviceId: String
    private let pasteboard: PasteboardAdapter
    private let transport: FrameTransportSink?
    private var epoch: UInt64 = 0
    private var lastObservedChangeCount: Int = -1
    public private(set) var lastSyncedContentHash: String?
    public private(set) var isEnabled: Bool = true
    public private(set) var direction: ClipboardDirection = .bidirectional
    public private(set) var isPeerReachable: Bool = false
    private var pollTask: Task<Void, Never>?

    public init(
        deviceId: String,
        pasteboard: PasteboardAdapter = SystemPasteboardAdapter(),
        transport: FrameTransportSink? = nil
    ) {
        self.deviceId = deviceId
        self.pasteboard = pasteboard
        self.transport = transport
    }

    public static func isConcealed(typeIdentifiers: Set<String>) -> Bool {
        !concealedTypes.isDisjoint(with: typeIdentifiers)
    }

    public func setEnabled(_ enabled: Bool) {
        self.isEnabled = enabled
        updatePollingState()
    }

    public func setDirection(_ direction: ClipboardDirection) {
        self.direction = direction
        updatePollingState()
    }

    public func setPeerReachable(_ reachable: Bool) {
        self.isPeerReachable = reachable
        updatePollingState()
    }

    private func updatePollingState() {
        if isEnabled && isPeerReachable && direction.allowsMacOutbound() {
            guard pollTask == nil else { return }
            pollTask = Task { [weak self] in
                while !Task.isCancelled {
                    try? await Task.sleep(for: .milliseconds(1000))
                    guard let self else { break }
                    _ = try? await self.pollLocalPasteboardOnce()
                }
            }
        } else {
            pollTask?.cancel()
            pollTask = nil
        }
    }

    @discardableResult
    public func pollLocalPasteboardOnce() async throws -> ClipboardSyncPayload? {
        guard isEnabled else { return nil }
        let sample = await pasteboard.readSample()
        guard sample.changeCount != lastObservedChangeCount else {
            return nil
        }
        lastObservedChangeCount = sample.changeCount
        return try await processLocalSample(sample)
    }

    public func processLocalSample(
        _ sample: PasteboardReadSample,
        now: Date = Date()
    ) async throws -> ClipboardSyncPayload? {
        guard isEnabled, direction.allowsMacOutbound() else { return nil }
        guard !Self.isConcealed(typeIdentifiers: sample.typeIdentifiers) else {
            return nil
        }

        let payload: ClipboardSyncPayload
        let preferBle: Bool

        if let text = sample.text, !text.isEmpty {
            let hash = Self.sha256Hex(Data(text.utf8))
            if hash == lastSyncedContentHash {
                return nil
            }
            epoch &+= 1
            payload = ClipboardSyncPayload(
                originDeviceId: deviceId,
                clipboardEpoch: epoch,
                contentSha256: hash,
                mimeType: "text/plain",
                text: text,
                isSensitive: false,
                timestampMs: UInt64(now.timeIntervalSince1970 * 1000)
            )
            preferBle = text.utf8.count <= Self.bleMaxPayloadBytes
        } else if let png = sample.pngData, !png.isEmpty, png.count <= Self.maxImageBytes {
            let hash = Self.sha256Hex(png)
            if hash == lastSyncedContentHash {
                return nil
            }
            epoch &+= 1
            payload = ClipboardSyncPayload(
                originDeviceId: deviceId,
                clipboardEpoch: epoch,
                contentSha256: hash,
                mimeType: "image/png",
                imageBase64: png.base64EncodedString(),
                isSensitive: false,
                timestampMs: UInt64(now.timeIntervalSince1970 * 1000)
            )
            preferBle = false
        } else {
            return nil
        }

        lastSyncedContentHash = payload.contentSha256
        if let transport {
            let json = try JSONEncoder().encode(payload)
            let frame = try WireFrame(messageType: .clipboardSync, sequenceId: epoch, payload: json)
            try await transport.sendFrame(frame, preferBleIfSmall: preferBle)
        }
        return payload
    }

    public func applyRemoteClipboard(_ payload: ClipboardSyncPayload) async throws {
        try payload.validate()
        guard isEnabled, direction.allowsMacInbound() else { return }
        // CRITICAL: Update lastSyncedContentHash BEFORE mutating NSPasteboard to prevent echo loops.
        lastSyncedContentHash = payload.contentSha256

        if payload.mimeType == "text/plain", let text = payload.text {
            await pasteboard.writeText(text)
            lastObservedChangeCount = await pasteboard.currentChangeCount()
        } else if payload.mimeType == "image/png",
                  let b64 = payload.imageBase64,
                  let data = Data(base64Encoded: b64),
                  data.count <= Self.maxImageBytes {
            await pasteboard.writePng(data)
            lastObservedChangeCount = await pasteboard.currentChangeCount()
        }
    }

    public static func sha256Hex(_ data: Data) -> String {
        SHA256.hash(data: data).map { String(format: "%02x", $0) }.joined()
    }
}
